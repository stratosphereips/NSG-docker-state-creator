def test_adv_edge_two_fails_exact_fail(tmp_path):
    """Exactly two consecutive failing samples is an outage (the
    min_consecutive=2 boundary, low side)."""
    rec, _ = run_adv("adv_edge_two_fails_exact", tmp_path)
    assert rec["verdict"] == "fail"
    assert rec["fail_1_1"] is True
    assert rec["attribution"] == "defender"
    assert "server/http_token" in rec["outage_services"]
    assert rec["fm11_restart"] is True      # recovered at the next tick
    assert rec["integrity"] == []


