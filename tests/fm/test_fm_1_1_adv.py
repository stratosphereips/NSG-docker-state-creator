from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

TESTS_FM_DIR = Path(__file__).resolve().parent
REPO_ROOT = TESTS_FM_DIR.parents[1]
SMS_HARNESS = REPO_ROOT / "fm_measurement" / "sms_harness"
for _p in (str(REPO_ROOT), str(SMS_HARNESS)):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from sms import fm11_outage  # noqa: E402

FAM = TESTS_FM_DIR / "fixtures" / "fm_1_1"


def run_adv(case: str, tmp_path: Path):
    """Copy the arm archive to tmp_path (measure writes into it), measure,
    and return the first unit's record."""
    archive = tmp_path / case
    shutil.copytree(FAM / case, archive)
    result = fm11_outage.measure(str(archive))
    assert result["fm"] == "1.1"
    return result["units"][0], result


