def test_adv_fixture_corpus_is_pristine_after_measure(tmp_path):
    """measure() writes fm11/fm11.json into the archive it reads; the
    battery copies to tmp_path, so the checked-in corpus must stay
    byte-identical (no stray outputs, no mutated probe records)."""
    before = {p.relative_to(FAM).as_posix(): p.read_bytes()
              for p in sorted(FAM.rglob("*")) if p.is_file()}
    run_adv("adv_edge_two_fails_exact", tmp_path)
    after = {p.relative_to(FAM).as_posix(): p.read_bytes()
             for p in sorted(FAM.rglob("*")) if p.is_file()}
    assert before == after
    assert not (FAM / "adv_edge_two_fails_exact" / "fm11").exists()


def test_adv_determinism_bit_for_bit(tmp_path):
    for case in ("adv_edge_two_fails_exact", "adv_tr_probes_deleted",
                 "adv_edge_ledger_rival_at_5"):
        first, _ = run_adv(case, tmp_path / "a")
        second, _ = run_adv(case, tmp_path / "b")
        assert json.dumps(first, sort_keys=True) == \
            json.dumps(second, sort_keys=True), case
